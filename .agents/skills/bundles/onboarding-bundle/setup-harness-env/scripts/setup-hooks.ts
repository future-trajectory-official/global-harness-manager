import { join } from "@std/path";
import { PROJECT_ROOT } from "../../../../../core/constants.ts";
import { fsUtil } from "../../../../../core/fs.ts";
import { executeCommand } from "../../../../../core/command.ts";
import { logger } from "../../../../../core/logger.ts";
import { MESSAGES } from "../../../../../core/messages.ts";

/**
 * Git Hooks をセットアップします
 */
export async function setupGitHooks(options: { gitDir?: string } = {}) {
  const gitDir = options.gitDir || join(PROJECT_ROOT, ".git");
  const hooksDir = join(gitDir, "hooks");
  const preCommitPath = join(hooksDir, "pre-commit");
  const prePushPath = join(hooksDir, "pre-push");

  // .git ディレクトリの存在確認
  if (!(await fsUtil.exists(gitDir))) {
    throw new Error(MESSAGES.SETUP.GIT_DIR_NOT_FOUND(gitDir));
  }

  if (!(await fsUtil.exists(hooksDir))) {
    await fsUtil.mkdir(hooksDir, { recursive: true });
  }

  // pre-commit フック: WIPコミット時の高速チェック (fmt + lint のみ)
  // テストや型チェックは省略し、コミット速度を最優先にする
  const preCommitScript = `#!/bin/sh
# pre-commit hook generated by deno task setup-hooks
# Purpose: Fast quality check on WIP commits (format + lint only)

echo "Running pre-commit checks..."

echo "[1/2] Format check..."
deno fmt --check
if [ $? -ne 0 ]; then
  echo "❌ Format check failed. Run 'deno fmt' to fix."
  exit 1
fi

echo "[2/2] Lint check..."
deno lint
if [ $? -ne 0 ]; then
  echo "❌ Lint check failed."
  exit 1
fi

echo "✅ Pre-commit checks passed!"
exit 0
`;

  // pre-push フック: プッシュ前の完全品質保証 (qa:cov = fmt + lint + type-check + test + coverage)
  // リモートへ反映する最終ゲートとして、カバレッジ付きの完全検証を行う
  const prePushScript = `#!/bin/sh
# pre-push hook generated by deno task setup-hooks
# Purpose: Full quality assurance before push (including coverage measurement)

echo "Running pre-push quality checks..."

echo "Running full QA with coverage (deno task qa:cov)..."
deno task qa:cov
if [ $? -ne 0 ]; then
  echo "❌ QA with coverage failed. Fix all issues before pushing."
  exit 1
fi

echo "✅ All pre-push checks passed!"
exit 0
`;

  try {
    // pre-commit フックの書き込み
    await fsUtil.writeTextFile(preCommitPath, preCommitScript);
    if (Deno.build.os !== "windows") {
      await executeCommand({
        cmd: "chmod",
        args: ["+x", preCommitPath],
      });
    }
    logger.success(MESSAGES.SETUP.HOOK_CONFIGURED(preCommitPath));

    // pre-push フックの書き込み
    await fsUtil.writeTextFile(prePushPath, prePushScript);
    if (Deno.build.os !== "windows") {
      await executeCommand({
        cmd: "chmod",
        args: ["+x", prePushPath],
      });
    }
    logger.success(MESSAGES.SETUP.HOOK_CONFIGURED(prePushPath));
  } catch (error) {
    throw new Error(
      MESSAGES.SETUP.HOOK_FAILED(error instanceof Error ? error.message : String(error)),
    );
  }
}

if (import.meta.main) {
  try {
    await setupGitHooks();
  } catch (error) {
    logger.error(error instanceof Error ? error.message : String(error));
    Deno.exit(1);
  }
}
