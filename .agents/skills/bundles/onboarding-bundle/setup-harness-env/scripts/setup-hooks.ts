import { join } from "@std/path";
import { PROJECT_ROOT } from "../../../../../core/constants.ts";
import { fsUtil } from "../../../../../core/fs.ts";
import { executeCommand } from "../../../../../core/command.ts";
import { logger } from "../../../../../core/logger.ts";

/**
 * Git Hooks をセットアップします
 */
export async function setupGitHooks(options: { gitDir?: string } = {}) {
  const gitDir = options.gitDir || join(PROJECT_ROOT, ".git");
  const hooksDir = join(gitDir, "hooks");
  const prePushPath = join(hooksDir, "pre-push");

  // .git ディレクトリの存在確認
  if (!(await fsUtil.exists(gitDir))) {
    throw new Error(`Git directory not found at ${gitDir}`);
  }

  if (!(await fsUtil.exists(hooksDir))) {
    await fsUtil.mkdir(hooksDir, { recursive: true });
  }

  const hookScript = `#!/bin/sh
# pre-push hook generated by deno task setup-hooks

echo "Running checks before push..."

echo "[1/3] Format check..."
deno fmt --check
if [ $? -ne 0 ]; then
  echo "❌ Format check failed. Run 'deno fmt' to fix."
  exit 1
fi

echo "[2/3] Lint check..."
deno lint
if [ $? -ne 0 ]; then
  echo "❌ Lint check failed."
  exit 1
fi

echo "[3/3] Tests..."
deno task test
if [ $? -ne 0 ]; then
  echo "❌ Tests failed."
  exit 1
fi

echo "✅ All checks passed!"
exit 0
`;

  try {
    await fsUtil.writeTextFile(prePushPath, hookScript);

    // 実行権限の付与
    if (Deno.build.os !== "windows") {
      await executeCommand({
        cmd: "chmod",
        args: ["+x", prePushPath],
      });
    }

    logger.success(`pre-push hook configured at ${prePushPath}`);
  } catch (error) {
    throw new Error(
      `Failed to configure git hook: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
}

if (import.meta.main) {
  try {
    await setupGitHooks();
  } catch (error) {
    logger.error(error instanceof Error ? error.message : String(error));
    Deno.exit(1);
  }
}
